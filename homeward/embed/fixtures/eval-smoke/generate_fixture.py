"""Generate synthetic eval-smoke fixture images.

These are solid-color PNG images with minor per-image variation.  They exist
ONLY to validate the harness arithmetic (Rank-1 correctness on an identical
image, disjoint gallery/query split).  They are NOT real animal photos and
prove nothing about real-world re-ID accuracy.

Run from this directory:
    python generate_fixture.py

Output structure (created alongside this script):
    gallery/dog1_photo1.png   — dog individual 1, gallery image
    gallery/cat1_photo1.png   — cat individual 1, gallery image
    query/dog1_photo2.png     — dog individual 1, query image (same color = Rank-1 match)
    query/cat1_photo2.png     — cat individual 1, query image (same color = Rank-1 match)
    query/dog2_photo1.png     — dog individual 2, query image (different color = should NOT match dog1)

License: generated by this script; no third-party rights.
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image

HERE = Path(__file__).parent


def solid(r: int, g: int, b: int, size: int = 64) -> Image.Image:
    """Create a solid-color RGB PNG image."""
    img = Image.new("RGB", (size, size), color=(r, g, b))
    return img


def save(img: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, format="PNG")
    print(f"  wrote {path.relative_to(HERE)}")


def main() -> None:
    print("Generating eval-smoke fixture images…")

    # dog1: orange-ish (255, 140, 0) in gallery, slightly lighter in query
    save(solid(255, 140, 0), HERE / "gallery" / "dog1_photo1.png")
    save(solid(255, 145, 10), HERE / "query" / "dog1_photo2.png")

    # cat1: steel-blue (70, 130, 180) in gallery, slightly lighter in query
    save(solid(70, 130, 180), HERE / "gallery" / "cat1_photo1.png")
    save(solid(75, 135, 185), HERE / "query" / "cat1_photo2.png")

    # dog2: lime-green (50, 205, 50) — a clearly different individual
    save(solid(50, 205, 50), HERE / "gallery" / "dog2_photo1.png")
    save(solid(55, 210, 55), HERE / "query" / "dog2_photo2.png")

    print("Done.")


if __name__ == "__main__":
    main()
